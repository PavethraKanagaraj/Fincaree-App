/**
 * Fincaree Design System — Docs Generator
 *
 * Rebuilds the Foundations/Semantics markdown tables directly from
 * design-system/figma/*.json, so the docs cannot drift from the tokens.
 *
 * Usage:  node scripts/generate-docs.mjs
 *
 * Both files are fully regenerated — do not hand-edit them.
 */

import { readFileSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const readJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'))

const primitives = readJson('design-system/figma/primitives.json')
const semantics = readJson('design-system/figma/semantic-colors.json')

/** Resolve a {Colors.*} / {Border.*} reference to a hex value. */
function resolve(ref, depth = 0) {
  if (typeof ref !== 'string' || !ref.startsWith('{') || depth > 8) return ref
  const path = ref.slice(1, -1).split('.')
  // primitives live under Colors.*; anything else is a semantic self-reference
  const source = path[0] === 'Colors' ? primitives : semantics
  let node = source
  for (const key of path) { node = node?.[key]; if (!node) break }
  if (!node) return ref
  const val = node.$value
  if (typeof val === 'string') return resolve(val, depth + 1)
  // a semantic token: follow its Light Mode so the docs show a concrete colour
  if (val && typeof val === 'object') return resolve(val['Light Mode'], depth + 1)
  return ref
}

/** Walk a token tree, yielding [slashPath, tokenObject] for every leaf. */
function leaves(node, path = []) {
  const out = []
  if (node && typeof node === 'object') {
    if ('$value' in node) return [[path.join('/'), node]]
    for (const [k, v] of Object.entries(node)) {
      if (!k.startsWith('$')) out.push(...leaves(v, [...path, k]))
    }
  }
  return out
}

// ── Semantics ────────────────────────────────────────────────────────────────
{
  const rows = leaves(semantics).filter(([p]) => p)
  const groups = new Map()
  for (const [path, tok] of rows) {
    const parts = path.split('/')
    const group = parts.length > 2 ? parts.slice(0, 2).join(' / ') : parts[0]
    if (!groups.has(group)) groups.set(group, [])
    const v = tok.$value ?? {}
    groups.get(group).push({
      name: path,
      light: String(resolve(v['Light Mode'])).toUpperCase(),
      dark: String(resolve(v['Dark Mode'])).toUpperCase(),
      desc: tok.$description ?? '',
    })
  }
  let md = `# Semantic Colors\n\n`
  md += `Source: \`figma/semantic-colors.json\` — generated by \`scripts/generate-docs.mjs\`.\n`
  md += `Do not hand-edit; run \`node scripts/generate-docs.mjs\` after changing the JSON.\n\n`
  md += `Aliases resolved from \`figma/primitives.json\`. Values shown are fully resolved hex.\n\n`
  md += `**${rows.length} tokens.**\n\n---\n`
  for (const [group, items] of groups) {
    md += `\n## ${group}\n\n| Token | Light Mode | Dark Mode |\n|---|---|---|\n`
    for (const i of items) md += `| \`${i.name}\` | \`${i.light}\` | \`${i.dark}\` |\n`
  }
  writeFileSync(join(root, 'design-system/docs/Semantics/semantic-colors.md'), md, 'utf8')
  console.log(`✅  semantic-colors.md — ${rows.length} tokens across ${groups.size} groups`)
}

// ── Primitives ───────────────────────────────────────────────────────────────
{
  const rows = leaves(primitives.Colors ?? {}, [])
  const groups = new Map()
  for (const [path, tok] of rows) {
    const parts = path.split('/')
    const group = parts.slice(0, -1).join('/')
    if (!groups.has(group)) groups.set(group, [])
    groups.get(group).push({ step: parts[parts.length - 1], hex: String(tok.$value).toUpperCase() })
  }
  const numeric = (a, b) => {
    const x = parseInt(a.step, 10), y = parseInt(b.step, 10)
    return Number.isNaN(x) || Number.isNaN(y) ? a.step.localeCompare(b.step) : x - y
  }
  let md = `# Primitives\n\n`
  md += `Source: \`figma/primitives.json\` — generated by \`scripts/generate-docs.mjs\`.\n`
  md += `Do not hand-edit; run \`node scripts/generate-docs.mjs\` after changing the JSON.\n\n`
  md += `**${rows.length} primitives.** Primitives are raw palette values — components must never\n`
  md += `reference them directly; they alias through \`1.Semantic color modes\`.\n\n---\n`
  for (const [group, items] of groups) {
    md += `\n## Colors/${group}\n\n| Step | Hex |\n|---|---|\n`
    for (const i of items.sort(numeric)) md += `| \`${i.step}\` | \`${i.hex}\` |\n`
  }
  writeFileSync(join(root, 'design-system/docs/Foundations/Primitives.md'), md, 'utf8')
  console.log(`✅  Primitives.md — ${rows.length} primitives across ${groups.size} ramps`)
}
