/* Named aliases kept for existing code. Each must land on a Figma step —
   the generator fails if one doesn't, so the names can't drift off-scale. */
const TYPE_ALIASES = {
  fontSize:      { 'font-size': { xs: 11, sm: 12, base: 14, md: 16, lg: 18, xl: 20, '2xl': 24, '3xl': 28, '4xl': 32, '5xl': 40 } },
  lineHeight:    { 'line-height': { xs: 16, sm: 18, base: 20, md: 24, lg: 28, xl: 32, '2xl': 36, '3xl': 40, '4xl': 44, '5xl': 52 } },
  letterSpacing: { tracking: { 'tight-2': -2, 'tight-1': -1, tight: -0.5, normal: 0, wide: 0.5, wider: 1 } },
}

/** Every Figma typography step as a variable, plus the named aliases. */
function typographyTokens() {
  const family = typography.fontFamily.base.$value
  const out = [
    `    --font-family: var(--font-geist-sans, "${family}"), -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;`,
  ]
  const scales = [
    ['fontSize', 'font-size', 'px'],
    ['lineHeight', 'line-height', 'px'],
    ['fontWeight', 'font-weight', ''],
    ['letterSpacing', 'letter-spacing', 'px'],
  ]
  for (const [key, prefix, unit] of scales) {
    out.push('', `    /* ${key} */`)
    for (const [step, t] of Object.entries(typography[key])) {
      out.push(`    --${prefix}-${step.toLowerCase()}: ${t.$value}${unit};`)
    }
    for (const [aliasPrefix, names] of Object.entries(TYPE_ALIASES[key] ?? {})) {
      out.push(`    /* ${aliasPrefix}-* aliases */`)
      for (const [name, value] of Object.entries(names)) {
        const step = Object.entries(typography[key]).find(([, t]) => t.$value === value)?.[0]
        if (!step) throw new Error(`--${aliasPrefix}-${name} (${value}) is not on the Figma ${key} scale`)
        out.push(`    --${aliasPrefix}-${name}: var(--${prefix}-${step.toLowerCase()});`)
      }
    }
  }
  return out.join('\n')
}

/* Component tokens whose Dark Mode alias in components.json differs from its
   Light Mode alias. 7.Components is otherwise light-only (its dark values are
   DERIVED below), so each authored dark alias is listed explicitly:
   token path → CSS variable. The generator fails if a listed token no longer
   has a distinct dark alias, so this list can't go stale silently. */
const COMPONENT_DARK_ALIASES = {
  'Switch/Thumb/Background/Disabled': '--switch-thumb-bg-disabled',
}

function componentDarkOverrides() {
  const out = []
  for (const [path, cssVar] of Object.entries(COMPONENT_DARK_ALIASES)) {
    const node = path.split('/').reduce((o, k) => o?.[k], components)
    if (!node?.$value) throw new Error(`components.json has no ${path}`)
    const light = node.$value['Light Mode'], dark = node.$value['Dark Mode']
    if (light === dark) throw new Error(`${path} no longer has a distinct Dark Mode alias`)
    const target = semanticCssName(dark.replace(/[{}]/g, '').split('.'))
    out.push(`    ${cssVar}: var(${target});   /* ${path} — Dark Mode ${dark} */`)
  }
  return out.join('\n')
}

/** Replaces the text between two markers; markers are required. */
function replaceBetween(css, start, end, body) {
  const s = css.indexOf(start)
  const e = css.indexOf(end)
  if (s < 0 || e < 0) throw new Error(`globals.css is missing the ${start} / ${end} markers`)
  return css.slice(0, s) + `${start}\n${body}\n    ${end}` + css.slice(e + end.length)
}

