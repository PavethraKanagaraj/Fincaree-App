/** --shadow-{xs…2xl} from the Shadow/Light/* or Shadow/Dark/* effect styles. */
function shadowTokens(set) {
  const out = []
  for (const [name, s] of Object.entries(shadows)) {
    if (!name.startsWith(`Shadow/${set}/`) || s.type !== 'DROP_SHADOW') continue
    const [r, g, b] = [1, 3, 5].map((i) => parseInt(s.color.slice(i, i + 2), 16))
    const step = name.split('/').pop().toLowerCase()
    out.push(`    --shadow-${step}: ${s.x}px ${s.y}px ${s.blur}px ${s.spread}px rgba(${r}, ${g}, ${b}, ${s.opacity});`)
  }
  if (!out.length) throw new Error(`shadows.json has no Shadow/${set}/* drop shadows`)
  return out.join('\n')
}

