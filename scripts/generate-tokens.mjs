// ── Primitive tokens — x_Primitives ─────────────────────────────────────────
function primitiveTokens() {
  const out = []
  const seen = new Set()
  const walk = (node, path) => {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith('$')) continue
      const p = [...path, k]
      if (v && typeof v === 'object' && '$value' in v) {
        const name = primitiveCssName(p)
        if (!name || seen.has(name)) continue
        seen.add(name)
        out.push(`    ${name}: ${v.$value.toLowerCase()};`)
      } else if (v && typeof v === 'object') {
        const before = out.length
        out.push(`    /* ${p.join(' / ')} */`)
        walk(v, p)
        if (out.length === before + 1) out.pop()
        else if (out.at(-1) !== '') out.push('')
      }
    }
  }
  walk(primitives.Colors, [])
  return { text: out.join('\n').trimEnd(), count: seen.size }
}

