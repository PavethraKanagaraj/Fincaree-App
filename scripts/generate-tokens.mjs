/** Infers a token's role from its name so the right ramp is used. */
function roleOf(name) {
  if (/(^|-)(bg|background|panel|surface|track|fill)(-|$)/.test(name)) return 'bg'
  if (/(^|-)(border|ring|divider|outline)(-|$)/.test(name)) return 'border'
  if (/(^|-)(icon|spinner|chevron|check|dot|caret)(-|$)/.test(name)) return 'icon'
  if (/(^|-)(text|label|hint|placeholder|value|title|caption|required|link)(-|$)/.test(name))
    return 'text'
  return null
}

/** Names already emitted by the semantic block — never re-derive these. */
const SEMANTIC_NAMES = new Set(SEMANTIC_MAP.flatMap(([, entries]) => entries.map(([v]) => v)))

/**
 * Scans the :root block of globals.css and derives a dark override for every
 * component token whose light value is a grey/white primitive.
 */
function derivedComponentTokens(cssText) {
  const start = cssText.indexOf(':root {')
  const end = cssText.indexOf('\n  }\n}', start)
  const rootBody = cssText.slice(start, end)

  // Many component tokens are authored as raw hex rather than var(--color-*),
  // so resolve those back to a primitive name before mapping.
  const hexToPrimitive = {}
  for (const [shade, node] of Object.entries(primitives.Colors.Primary.Grey)) {
    if (typeof node?.$value === 'string') {
      hexToPrimitive[node.$value.toLowerCase()] = `grey-${shade}`
    }
  }
  hexToPrimitive[primitives.Colors.Base.white.$value.toLowerCase()] = 'white'

  const re = /--([a-z0-9-]+):\s*([^;]+);/g
  const out = []
  const seen = new Set()
  let m
  while ((m = re.exec(rootBody))) {
    const name = m[1]
    const value = m[2].trim()

    if (name.startsWith('color-')) continue        // primitives themselves
    if (SEMANTIC_NAMES.has(`--${name}`)) continue   // handled by semantic block
    if (seen.has(name)) continue

    let primitive = null
    const varMatch = value.match(/^var\(--color-([a-z]+(?:-\d+)?)\)$/)
    if (varMatch) primitive = varMatch[1]
    else if (/^#[0-9a-fA-F]{6}$/.test(value)) primitive = hexToPrimitive[value.toLowerCase()]

    // Only greys and white are themed; brand/status hues pass through, as do
    // 8-digit hexes (focus halos) and any non-colour value.
    if (!primitive || !/^(white|grey-\d+)$/.test(primitive)) continue

    const role = roleOf(name)
    if (!role) continue
    const target = ROLE_MAPS[role][primitive]
    if (!target) continue

    seen.add(name)
    out.push(`    --${name}: var(${target});`)
  }
  return { lines: out, count: out.length }
}

/* ── Semantic aliasing for generated component tokens ───────────────────────
   Component tokens must reference the semantic layer, never a primitive, so
   they inherit theming. After rendering a component block we swap any
   var(--color-*) for the semantic token of the same role that resolves to the
   identical light value. If no such token exists the primitive is left in
   place and reported, since inventing one is a design decision.          */
const ROLE_PREFIX = { bg: '--bg-', border: '--border-', icon: '--icon-', text: '--text-' }
const STATE_WORDS = ['disabled', 'placeholder', 'hover', 'inverse']
const CANONICAL = ['primary', 'secondary', 'tertiary', 'quaternary', 'placeholder', 'disabled']

const unaliased = []

/** semantic css var name → its Light Mode value, e.g. 'var(--color-grey-900)' */
function semanticLightIndex() {
  const prev = MODE
  MODE = 'Light Mode'
  const index = {}
  for (const [, entries] of SEMANTIC_MAP) {
    for (const [name, path] of entries) {
      const node = path.split('.').reduce((o, k) => o?.[k], semantics)
      if (node) index[name] = cv(node)
    }
  }
  MODE = prev
  return index
}

function chooseSemantic(candidates, tokenName) {
  for (const w of STATE_WORDS) {
    if (tokenName.includes(w)) {
      const hit = candidates.filter((c) => c.includes(w))
      if (hit.length) return hit[0]
    }
  }
  const plain = candidates.filter((c) => !STATE_WORDS.some((w) => c.includes(w)))
  const pool = plain.length ? plain : candidates
  pool.sort((a, b) => {
    const ra = CANONICAL.findIndex((r) => a.endsWith(r))
    const rb = CANONICAL.findIndex((r) => b.endsWith(r))
    return (ra < 0 ? 99 : ra) - (rb < 0 ? 99 : rb) || a.length - b.length
  })
  return pool[0]
}

function semanticize(text) {
  const index = semanticLightIndex()
  return text.replace(
    /(--([a-z0-9-]+):(\s*))var\(--color-([a-z0-9-]+)\);/g,
    (full, prefix, name, _ws, prim) => {
      const role = roleOf(name)
      if (!role) return full
      const pfx = ROLE_PREFIX[role]
      const want = `var(--color-${prim})`
      const candidates = Object.keys(index).filter(
        (sn) => sn.startsWith(pfx) && index[sn] === want
      )
      if (!candidates.length) {
        unaliased.push(`--${name} (${want})`)
        return full
      }
      return `${prefix}var(${chooseSemantic(candidates, name)});`
    }
  )
}

const missingPaths = []

/** Resolves a dotted path in semantic-colors.json to a CSS var string */
function sem(path) {
  const node = path.split('.').reduce((o, k) => o?.[k], semantics)
  if (!node) { missingPaths.push(path); return null }
  return cv(node)
}

/** Renders the full semantic token list for the current MODE */
function semanticTokens() {
  const out = []
  for (const [group, entries] of SEMANTIC_MAP) {
    out.push(`    /* ${group} */`)
    for (const [varName, path] of entries) {
      const value = sem(path)
      if (value) out.push(`    ${varName}: ${value};`)
    }
    out.push('')
  }
  return out.join('\n').trimEnd()
}

